// Dynamic scenario test-data prefill.
// The backend is language-specific: V2 derives Java/Spring DTO samples, while
// V3 derives Python/FastAPI/Pydantic samples. This file only renders the result.
(function () {
    const ids = {
        method: "newScenarioMethod",
        endpoint: "newScenarioEndpoint",
        request: "newScenarioRequestJson",
        response: "newScenarioExpectedResponse",
        db: "newScenarioExpectedDbEffect"
    };

    function element(name) {
        return document.getElementById(ids[name]);
    }

    function pretty(value) {
        if (value === null || value === undefined) return "";
        if (typeof value === "string") return value;
        return JSON.stringify(value, null, 2);
    }

    function setGenerated(field, value) {
        if (!field) return;
        // Replace previous generated values when operation changes, but never
        // overwrite data that the developer typed manually.
        if (field.value.trim() && field.dataset.autoGenerated !== "true") return;
        field.value = pretty(value);
        field.dataset.autoGenerated = "true";
    }

    async function populateScenarioTestData() {
        const method = (element("method")?.value || "").trim().toUpperCase();
        const endpoint = (element("endpoint")?.value || "").trim();
        if (!method || !endpoint) return;

        const requestField = element("request");
        const responseField = element("response");
        const dbField = element("db");

        try {
            const response = await fetch(
                `/api/endpoint-flow/sample-data?http_method=${encodeURIComponent(method)}&endpoint=${encodeURIComponent(endpoint)}`
            );
            const text = await response.text();
            let data = {};
            try { data = text ? JSON.parse(text) : {}; } catch (_) { data = {}; }
            if (!response.ok) throw new Error(data.detail || `HTTP ${response.status}`);

            setGenerated(requestField, data.request_json);
            setGenerated(responseField, data.expected_response_json);
            setGenerated(dbField, data.expected_db_effect);
        } catch (error) {
            // Sample generation is a convenience only. Scenario registration
            // must remain usable even for unusual framework/DTO constructs.
            console.debug("Scenario sample-data generation skipped:", error);
        }
    }

    function markManual(event) {
        event.currentTarget.dataset.autoGenerated = "false";
    }

    function wire() {
        const endpoint = element("endpoint");
        if (endpoint && endpoint.dataset.sampleDataWired !== "true") {
            endpoint.addEventListener("change", populateScenarioTestData);
            endpoint.dataset.sampleDataWired = "true";
        }
        [element("request"), element("response"), element("db")].forEach(field => {
            if (field && field.dataset.sampleDataInputWired !== "true") {
                field.addEventListener("input", markManual);
                field.dataset.sampleDataInputWired = "true";
            }
        });
    }

    document.addEventListener("DOMContentLoaded", wire);
    // Modal contents already exist in the DOM, but this also supports future
    // dynamic rendering without coupling to project-ui.js implementation.
    const observer = new MutationObserver(wire);
    document.addEventListener("DOMContentLoaded", () => {
        observer.observe(document.body, {childList: true, subtree: true});
    });

    window.populateScenarioTestData = populateScenarioTestData;
})();
